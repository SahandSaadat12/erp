"""
Window / taskbar icon that follows the active theme.

icons/app_<Theme>.ico are generated by tools/make_icons.py.
"""

import os
import sys

from paths import resource_path

_APP_ID = "ERP.ProjectManagement.App"


def _icon_file(theme_name):
    safe = str(theme_name).replace(" ", "_")
    path = resource_path("icons", f"app_{safe}.ico")
    if not os.path.exists(path):
        path = resource_path("icons", "app.ico")
    return path if os.path.exists(path) else None


def set_taskbar_identity():
    """Own taskbar group (so Windows shows OUR icon, not python.exe's)."""
    if sys.platform != "win32":
        return
    try:
        import ctypes
        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(_APP_ID)
    except Exception:
        pass


def apply_icon(window, theme_name):
    """Set the themed icon on one window (CTk / CTkToplevel / Toplevel)."""
    if sys.platform != "win32":
        return
    path = _icon_file(theme_name)
    if not path:
        return
    try:
        # customtkinter swaps in its own blue icon 200 ms after start-up unless
        # iconbitmap() was called, so we call it right away (and once more
        # later as a safety net).
        window.iconbitmap(path)
        window.after(300, lambda: _safe(window, path))
    except Exception:
        pass


def _safe(window, path):
    try:
        if window.winfo_exists():
            window.iconbitmap(path)
    except Exception:
        pass


def install_for_all_windows(theme_name):
    """Every CustomTkinter dialog / popup gets the themed icon automatically."""
    try:
        import customtkinter as ctk

        original = ctk.CTkToplevel.__init__

        def patched(self, *args, **kwargs):
            original(self, *args, **kwargs)
            apply_icon(self, theme_name)

        ctk.CTkToplevel.__init__ = patched
    except Exception:
        pass
