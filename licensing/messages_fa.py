def rtl(text):
    return "\n".join(RLM + line if line.strip() else line for line in text.split("\n"))


def render(code, **fields):
    """-> (title, body) with placeholders filled and RTL marks added."""
    title, body = MESSAGES.get(code, MESSAGES["INTERNAL"])
    safe = {k: ("" if v is None else v) for k, v in fields.items()}
    try:
        body = body.format(**{**{"path": "", "machine_id": "", "detail": "",
                                  "expires_at": "", "license_id": "", "days": ""}, **safe})
    except Exception:
        pass
    return rtl(title), rtl(body)
